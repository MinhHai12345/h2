CREATE TABLE match_player_statistics (
    id BIGINT NOT NULL AUTO_INCREMENT,
    match_id BIGINT NOT NULL,
    player_id BIGINT NOT NULL,
    provider VARCHAR(40) NOT NULL,
    rating DECIMAL(8, 3) NULL,
    minutes_played INT NULL,
    goals INT NULL,
    assists INT NULL,
    total_shots INT NULL,
    shots_on_target INT NULL,
    accurate_passes INT NULL,
    total_passes INT NULL,
    key_passes INT NULL,
    tackles INT NULL,
    interceptions INT NULL,
    clearances INT NULL,
    expected_goals DECIMAL(12, 4) NULL,
    expected_assists DECIMAL(12, 4) NULL,
    raw_statistics LONGTEXT NULL,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    CONSTRAINT fk_match_player_statistics_match FOREIGN KEY (match_id) REFERENCES matches (id) ON DELETE CASCADE,
    CONSTRAINT fk_match_player_statistics_player FOREIGN KEY (player_id) REFERENCES players (id),
    CONSTRAINT uk_match_player_statistics_source UNIQUE (match_id, player_id, provider),
    INDEX idx_match_player_statistics_player (player_id),
    INDEX idx_match_player_statistics_match_provider (match_id, provider)
) ENGINE=InnoDB;
